"""Train/evaluate or infer the BFZI V150 fractional-memory neural surrogate.

Training teacher is generated by examples.bfzi_frac_data from the independent
BFZI electromagnetic solver and its 450-dimensional three-material heat model.

Examples:
  python -m examples.bfzi_frac train --data runs/m4_frac_teacher.npz
  python -m examples.bfzi_frac infer --model runs/m4_frac.pt --voltage 100
"""
from __future__ import annotations
import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from sdfmpneo_bfzi.frac_memory import FracNet,build_sources,predict


def dataset(path,rank=20):
    with np.load(path) as d:
        t=np.asarray(d["time_s"],float)
        vin=np.asarray(d["voltage_v"],float)
        temp=np.asarray(d["temp_K"],float)
        z=np.asarray(d["z6"],float)
        cur=np.asarray(d["currents_A"])
        eta=np.asarray(d["eta"],float)
        train=np.asarray(d["train"],bool)
        nsea=int(d["nsea"]); npkg=int(d["npkg"])
        amb=float(d["ambient_K"])
        ext=np.asarray(d["external_z"],complex)
        cases=json.loads(str(d["cases_json"]))
    # Withhold one full switching program per training voltage for
    # validation. The 10 physically generated test histories stay untouched.
    ids=np.flatnonzero(train)
    val=ids[3::4]
    fit=np.setdiff1d(ids,val)
    rise=temp-amb
    widths=(slice(None,nsea),
            slice(nsea,nsea+2*npkg),
            slice(nsea+2*npkg,None))
    block=np.ones(temp.shape[-1])
    for sl in widths:
        block[sl]=max(float(np.std(rise[fit,:,sl])),1e-3)
    weighted=rise[fit].reshape(-1,rise.shape[-1])/block
    _,_,vh=np.linalg.svd(weighted,full_matrices=False)
    rank=min(int(rank),len(vh))
    basis=vh[:rank].T.copy()
    coef=(rise/block)@basis
    z0=z[0,0].copy()
    yy=np.concatenate([coef,z-z0],axis=-1)
    raw_std=np.std(yy[fit,1:],axis=(0,1))
    c_floor=max(float(np.max(raw_std[:rank]))*.002,1e-5)
    z_floor=max(float(np.max(raw_std[rank:]))*.002,1e-8)
    scale=np.maximum(raw_std,np.r_[
        np.full(rank,c_floor),np.full(6,z_floor)])
    y=yy/scale
    src=build_sources(vin,z,ext)
    src_scale=np.maximum(np.max(src[fit],axis=(0,1)),1e-4)
    return dict(times=t,v=vin,temp=temp,z=z,cur=cur,eta=eta,
                train=fit,val=val,test=np.flatnonzero(~train),
                cases=cases,nsea=nsea,npkg=npkg,amb=amb,
                ext=ext,src=src/src_scale,
                src_scale=src_scale,basis=basis,t_scale=block,
                z0=z0,scale=scale,y=y,rank=rank)


def checkpoint(model,d):
    return dict(
        state=model.state_dict(),mode=model.mode,nout=model.nout,
        basis=torch.tensor(d["basis"],dtype=torch.float32),
        t_scale=torch.tensor(d["t_scale"],dtype=torch.float32),
        y_scale=torch.tensor(d["scale"],dtype=torch.float32),
        src_scale=torch.tensor(d["src_scale"],dtype=torch.float32),
        z0=torch.tensor(d["z0"],dtype=torch.float32),
        external_z=torch.tensor(d["ext"],dtype=torch.complex64),
        ambient=float(d["amb"]),nsea=d["nsea"],npkg=d["npkg"])


def load(path):
    ck=torch.load(path,map_location="cpu",weights_only=True)
    model=FracNet(ck["nout"],ck["mode"])
    model.load_state_dict(ck["state"])
    model.eval()
    return model,ck


def fit_one(d,mode,epochs=900,patience=180):
    torch.manual_seed(41)
    model=FracNet(d["rank"]+6,mode)
    train=np.asarray(d["train"],int)
    val=np.asarray(d["val"],int)
    src=torch.tensor(d["src"],dtype=torch.float32)
    label=torch.tensor(d["y"],dtype=torch.float32)
    op=torch.optim.Adam(model.parameters(),lr=.003)
    best=1e30; best_state=None; best_epoch=0
    t0=time.perf_counter()
    for epoch in range(epochs):
        model.train()
        op.zero_grad(set_to_none=True)
        pr=model(src[train],d["times"])
        loss=torch.mean((pr-label[train])**2)
        loss.backward()
        op.step()
        model.eval()
        with torch.no_grad():
            vloss=float(torch.mean(
                (model(src[val],d["times"])-label[val])**2))
        if vloss<best-1e-7:
            best=vloss
            best_epoch=epoch+1
            best_state={k:v.detach().clone()
                        for k,v in model.state_dict().items()}
        if epoch+1-best_epoch>=patience:
            break
    model.load_state_dict(best_state)
    model.eval()
    params=(model.orders().detach().cpu().numpy().tolist())
    return model,dict(mode=mode,epochs=epoch+1,best_epoch=best_epoch,
                      val_loss=best,learned_orders=params,
                      training_sec=time.perf_counter()-t0)


def eval_one(model,ck,d,ids):
    metrics=[]
    pred_temp=[];pred_z=[];pred_eta=[];pred_i=[]
    start=time.perf_counter()
    for idx in ids:
        res=predict(model,ck,d["v"][idx],d["times"])
        th=res["temp_K"];z=res["z6"]
        direct=d["temp"][idx];zref=d["z"][idx]
        ns=d["nsea"];npack=d["npkg"]*2
        diff=th-direct
        z_delta=zref-d["z0"]
        iz=res["current_A"];it=d["cur"][idx]
        err=dict(
            id=int(idx),voltage_v=d["cases"][int(idx)]["voltage_v"],
            windows_s=d["cases"][int(idx)]["windows_s"],
            sea_max_K=float(np.max(abs(diff[:,:ns]))),
            pkg_max_K=float(np.max(abs(diff[:,ns:ns+npack]))),
            cu_max_K=float(np.max(abs(diff[:,ns+npack:]))),
            temp_relative_L2=float(np.linalg.norm(diff)/
                       max(np.linalg.norm(direct-d["amb"]),1e-12)),
            Z_relative_L2=float(np.linalg.norm(z-zref)/
                       max(np.linalg.norm(zref),1e-12)),
            dynamic_Z_relative_L2=float(np.linalg.norm(z-zref)/
                       max(np.linalg.norm(z_delta),1e-12)),
            current_relative_L2=float(np.linalg.norm(iz-it)/
                       max(np.linalg.norm(it),1e-12)),
            eta_max_abs=float(np.max(abs(res["eta"]-d["eta"][idx]))))
        metrics.append(err)
        pred_temp.append(th);pred_z.append(z)
        pred_eta.append(res["eta"]);pred_i.append(iz)
    elapsed=time.perf_counter()-start
    agg={
        "test_cases":len(ids),
        "rollout_sec":elapsed,
        "seconds_per_21_step_history":elapsed/max(len(ids),1),
    }
    for k in ("sea_max_K","pkg_max_K","cu_max_K","temp_relative_L2",
              "Z_relative_L2","dynamic_Z_relative_L2",
              "current_relative_L2","eta_max_abs"):
        agg[k+"_max"]=float(max(m[k] for m in metrics))
        agg[k+"_mean"]=float(np.mean([m[k] for m in metrics]))
    return agg,metrics,dict(
        temp_K=np.asarray(pred_temp),z6=np.asarray(pred_z),
        eta=np.asarray(pred_eta),currents_A=np.asarray(pred_i))


def train(args):
    d=dataset(args.data,args.rank)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    result=dict(data=str(args.data),bfzi_teacher_case_count=len(d["v"]),
                full_space_thermal_states=d["temp"].shape[-1],
                train_cases=len(d["train"]),validation_cases=len(d["val"]),
                test_cases=len(d["test"]),
                times_per_case=len(d["times"]), 
                fractional_kernel="positive logarithmic SOE for t^(alpha-1), 0<alpha<1",
                electrical_feedback="solve predicted complex 2-port Z at every interval")
    for mode in ("frac","exp"):
        net,train_info=fit_one(
            d,mode,epochs=args.epochs,patience=args.patience)
        ck=checkpoint(net,d)
        path=args.model if mode=="frac" else args.model.with_name(
            args.model.stem+"_exp"+args.model.suffix)
        path.parent.mkdir(parents=True,exist_ok=True)
        torch.save(ck,path)
        agg,items,fields=eval_one(net,ck,d,d["test"])
        result[mode]=dict(model=str(path),train=train_info,
                          heldout=agg,case_metrics=items)
        if mode=="frac":
            np.savez_compressed(
                args.out.with_suffix(".npz"),
                time_s=d["times"],case_ids=d["test"],
                voltage_v=d["v"][d["test"]],
                temp_true_K=d["temp"][d["test"]],
                temp_pred_K=fields["temp_K"],
                z_true=d["z"][d["test"]],
                z_pred=fields["z6"],
                eta_true=d["eta"][d["test"]],
                eta_pred=fields["eta"])
        print(json.dumps(dict(mode=mode,model=str(path),train=train_info,
                              heldout=agg),indent=2),flush=True)
    a=result["frac"]["heldout"];b=result["exp"]["heldout"]
    result["comparison"]=dict(
        fractional_vs_exponential_pkg_error_ratio=a["pkg_max_K_mean"]/
                                                 max(b["pkg_max_K_mean"],1e-12),
        fractional_vs_exponential_dynamic_Z_ratio=a["dynamic_Z_relative_L2_mean"]/
                                                  max(b["dynamic_Z_relative_L2_mean"],1e-12))
    args.out.write_text(json.dumps(result,indent=2),encoding="utf-8")
    print("METRICS",args.out,flush=True)


def infer(args):
    model,ck=load(args.model)
    times=np.arange(0,args.horizon+args.step/2,args.step,dtype=float)
    vin=np.array([
        args.voltage if t<=args.heat or t>args.heat+args.cool
        else 0 for t in times],float)
    t0=time.perf_counter()
    r=predict(model,ck,vin,times)
    ns=int(ck["nsea"]);npkg=int(ck["npkg"])
    rows=[]
    for k,t in enumerate(times):
        x=r["temp_K"][k]
        rows.append(dict(time_s=float(t),drive_V=float(vin[k]),
            Tsea_max_K=float(np.max(x[:ns])),
            Tpkg_mean_K=np.mean(x[ns:ns+2*npkg].reshape(2,npkg),axis=1).tolist(),
            Tpkg_max_K=np.max(x[ns:ns+2*npkg].reshape(2,npkg),axis=1).tolist(),
            Tcu_K=x[ns+2*npkg:].tolist(),
            Z6=r["z6"][k].tolist(),
            efficiency=float(r["eta"][k])))
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(dict(
        model=str(args.model),mode=model.mode,
        inference_sec=time.perf_counter()-t0,
        time_step_s=args.step,trace=rows),indent=2),encoding="utf-8")
    np.savez_compressed(args.out.with_suffix(".npz"),time_s=times,
                        voltage_v=vin,**r)
    print(json.dumps(dict(out=str(args.out),steps=len(times),
        Tpkg_last_K=rows[-1]["Tpkg_max_K"],Tcu_last_K=rows[-1]["Tcu_K"],
        efficiency_last=rows[-1]["efficiency"]),indent=2))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("task",choices=("train","infer"))
    p.add_argument("--data",type=Path,
                   default=Path("runs/m4_frac_teacher.npz"))
    p.add_argument("--model",type=Path,
                   default=Path("runs/m4_frac.pt"))
    p.add_argument("--out",type=Path,default=None)
    p.add_argument("--rank",type=int,default=20)
    p.add_argument("--epochs",type=int,default=900)
    p.add_argument("--patience",type=int,default=180)
    p.add_argument("--voltage",type=float,default=100)
    p.add_argument("--heat",type=float,default=240)
    p.add_argument("--cool",type=float,default=180)
    p.add_argument("--horizon",type=float,default=600)
    p.add_argument("--step",type=float,default=30)
    args=p.parse_args()
    torch.set_num_threads(2)
    if args.out is None:
        args.out=Path("runs/m4_frac_metrics.json"
                      if args.task=="train" else "runs/m4_frac_infer.json")
    if args.task=="train":
        train(args)
    else:
        infer(args)


if __name__=="__main__":
    main()
