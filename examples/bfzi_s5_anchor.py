"""Build one BFZI V150 S5 cold anchor and neural thermal basis.

Frozen U01-U12 are validation cases only. Use new non-frozen geometry keys to
produce training anchors. No dynamic BFZI truth is generated by this script.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import time

import numpy as np

from examples.bfzi_param import create, originals
from examples.bfzi_physics_recheck import GRIDS, build
from sdfmpneo_bfzi.geom_heat import GeomHeat
from sdfmpneo_bfzi.geom_rom import GeomHeatROM
from sdfmpneo_bfzi.s5_bridge import from_skin


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--bfzi-root', type=Path, required=True)
    p.add_argument('--spec-file', type=Path, required=True)
    p.add_argument('--key', required=True)
    p.add_argument('--role', choices=['validation', 'training'], default='validation')
    p.add_argument('--grid', choices=['ultra', 'superfine'], default='ultra')
    p.add_argument('--grid-max-nodes', type=int, default=4000)
    p.add_argument('--rank', type=int, default=32)
    p.add_argument('--runs', type=Path, default=Path('runs'))
    p.add_argument('--output', type=Path, default=None)
    p.add_argument('--teacher', type=Path, default=None)
    a = p.parse_args()
    if a.role == 'training' and a.key in {f'U{i:02d}' for i in range(1, 13)}:
        p.error('U01-U12 are frozen independent physical validation cases')
    spec = json.loads(a.spec_file.read_text(encoding='utf-8'))['cases'][a.key]
    parent = 'p03' if spec['donor'] == 'g1' else 'p07'
    ext = GeomHeat.load(a.runs / f'bfzi_pose_{parent}_disjoint_anchor.npz').ext
    bf, v150 = originals(a.bfzi_root)
    xz, y = GRIDS[a.grid]
    clock = time.perf_counter()
    data, _ = create(bf, v150, 'M4', **spec['geometry'], sea_void='oriented',
                     physical_box_only=True, grid_xz=xz, grid_y=y,
                     grid_max_nodes=a.grid_max_nodes)
    mat = spec.get('thermal', {})
    opts = dict(alpha=spec['alpha_per_K'], source_order=5,
                skin=mat.get('skin_m', .002),
                ins_k=mat.get('ins_k', .25),
                ins_t=mat.get('ins_t'),
                pkg_k=mat.get('pkg_k', .25),
                pkg_sea_h=mat.get('pkg_sea_h', 20.),
                sea_max=373.15, cu_max=1357.77, pkg_max=None)
    et = build(data, bf, ext, opts)
    thickness = opts['ins_t']
    if thickness is None:
        thickness = float(np.mean(et.cu_ins_layers))
    therm = np.array([opts['alpha'], opts['ins_k'], thickness,
                      opts['pkg_k'], opts['pkg_sea_h']])
    head = from_skin(et.model, et, ext, thermal=therm)
    rom = GeomHeatROM.build(head, rank=a.rank)
    prefix = a.output or a.runs / f'bfzi_s5_{a.key}_{a.grid}'
    prefix.parent.mkdir(parents=True, exist_ok=True)
    head.save(str(prefix) + '_anchor.npz')
    rom.save(str(prefix) + '_rom.npz')
    result = dict(case=a.key, role=a.role, grid=a.grid, source_order=5,
                  wet_nodes=head.nwet, skin_nodes=head.nskin,
                  heat_nodes=len(head.cap), rom_rank=rom.rank,
                  thermal_params=therm.tolist(),
                  offline_seconds=time.perf_counter()-clock,
                  anchor=str(prefix)+'_anchor.npz',
                  rom=str(prefix)+'_rom.npz')
    if a.teacher:
        from examples.bfzi_geom_neural import read
        row = read(a.teacher, rom)
        result['teacher_times'] = len(row['time'])
        result['teacher_heat_state_shape'] = list(row['a'].shape)
        result['teacher_full_temp_shape'] = list(row['temp_K'].shape)
    (Path(str(prefix)+'_metadata.json')).write_text(
        json.dumps(result, indent=2), encoding='utf-8')
    print(json.dumps(result, indent=2), flush=True)


if __name__ == '__main__':
    main()
